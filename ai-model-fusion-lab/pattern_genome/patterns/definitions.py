def all_records() -> list:
    recs = [r.validate() for r in PATTERNS]
    ids = [r.pattern_id for r in recs]
    assert len(ids) == len(set(ids)) == 100, "registry must hold exactly 100 unique patterns"
    return recs


def by_phase(phase: str) -> list:
    return [r for r in all_records() if r.phase == phase]


