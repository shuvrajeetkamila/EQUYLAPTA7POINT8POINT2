def P(pid, name, family, phase, detector, null, hyp, feat=None, abl="", res="",
      xfer="", min_ev=3, fail=None, eff="MEDIUM", arch="MEDIUM", desc=""):
    return PatternRecord(
        pattern_id=pid, name=name, family=F[family],
        description=desc or hyp[:160],
        computational_hypothesis=hyp,
        measurable_features=feat or [],
        discovery_algorithm=f"primitive:{detector}",
        null_model=null,
        ablation_strategy=abl, restoration_strategy=res, transfer_strategy=xfer,
        minimum_evidence=min_ev, failure_conditions=fail or [
            "detection not significant vs null",
            "ablation has no capability effect beyond floor",
            "effect not specific to target capability",
            "result does not reproduce across seeds"],
        parameter_efficiency=eff, architecture_dependence=arch,
        phase=phase, detector=detector)


